CREATE TABLE IF NOT EXISTS digests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot TEXT NOT NULL,
  trigger TEXT NOT NULL,
  ran_at TEXT NOT NULL,
  cutoff_at TEXT NOT NULL,
  item_count INTEGER NOT NULL,
  note TEXT,
  daily_status TEXT,
  daily_date TEXT,
  daily_lead TEXT,
  daily_url TEXT,
  glossary_note TEXT,
  feishu_url TEXT,
  feishu_note TEXT,
  brief_json TEXT
);

CREATE TABLE IF NOT EXISTS news_items (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  original_title TEXT,
  summary TEXT,
  source_name TEXT NOT NULL,
  link_aihot TEXT NOT NULL,
  link_original TEXT NOT NULL,
  published_at TEXT,
  discovered_at TEXT NOT NULL,
  category TEXT,
  score INTEGER,
  reason TEXT,
  content_hash TEXT NOT NULL,
  glossary_done INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL,
  selected INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS digest_items (
  digest_id INTEGER NOT NULL REFERENCES digests(id),
  news_id TEXT NOT NULL REFERENCES news_items(id),
  change_kind TEXT NOT NULL,
  PRIMARY KEY (digest_id, news_id)
);

CREATE TABLE IF NOT EXISTS glossary_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  aliases TEXT NOT NULL,
  kind TEXT NOT NULL,
  familiarity TEXT NOT NULL,
  summary_zh TEXT NOT NULL,
  wiki_url TEXT,
  wiki_title TEXT,
  wiki_lang TEXT,
  status TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS news_glossary (
  news_id TEXT NOT NULL REFERENCES news_items(id),
  entry_id INTEGER NOT NULL REFERENCES glossary_entries(id),
  context_note TEXT NOT NULL,
  PRIMARY KEY (news_id, entry_id)
);

CREATE TABLE IF NOT EXISTS sync_state (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS hot_topics (
  rank INTEGER PRIMARY KEY,
  item_id TEXT,
  title TEXT NOT NULL,
  source_name TEXT,
  link_aihot TEXT,
  link_original TEXT,
  source_count INTEGER,
  fetched_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS corpus_docs (
  kind TEXT NOT NULL,
  doc_key TEXT NOT NULL,
  title TEXT,
  payload TEXT NOT NULL,
  fetched_at TEXT NOT NULL,
  PRIMARY KEY (kind, doc_key)
);

CREATE INDEX IF NOT EXISTS idx_news_glossary_entry ON news_glossary(entry_id);
CREATE INDEX IF NOT EXISTS idx_digest_ran ON digests(ran_at);
CREATE INDEX IF NOT EXISTS idx_news_discovered ON news_items(discovered_at);
